const lang = ref<Lang>(readCache<Lang>('lang') ?? 'zh')
const zhCats = ref<Record<string, string>>({})
let zhLoaded = false

async function loadZhCats(): Promise<void> {
  if (zhLoaded) return
  zhLoaded = true
  try {
    const mod = await import('../data/taxonomy-zh.json')
    zhCats.value = (mod.default ?? mod) as Record<string, string>
  } catch {
    zhCats.value = {}
  }
  // 正本是 taxonomy_zh 表（後台改得到，公開讀）；讀不到就維持打包進來的那份
  const { data } = await supabase.from('taxonomy_zh').select('name,zh')
  const rows = (data ?? []) as Array<{ name: string; zh: string }>
  if (rows.length) {
    const next = { ...zhCats.value }
    for (const r of rows) next[r.name] = r.zh
    zhCats.value = next
  }
}
